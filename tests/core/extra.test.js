test('3MF: components with their own matrices, units in cm, modifier parts skipped, non-printable items', () => {
  const pos = cube(10);
  const verts = [], tris = [], map = new Map();
  for (let i = 0; i < pos.length; i += 3) { const k = `${pos[i]} ${pos[i + 1]} ${pos[i + 2]}`; if (!map.has(k)) { map.set(k, verts.length); verts.push(k); } tris.push(map.get(k)); }
  const mesh = `<mesh><vertices>${verts.map((v) => { const [a, b, c] = v.split(' '); return `<vertex x="${a}" y="${b}" z="${c}"/>`; }).join('')}</vertices><triangles>${tris.reduce((s, _, i) => (i % 3 ? s : s + `<triangle v1="${tris[i]}" v2="${tris[i + 1]}" v3="${tris[i + 2]}" paint_supports="4"/>`), '')}</triangles></mesh>`;
  const model = `<model unit="centimeter" xmlns:p="http://schemas.microsoft.com/3dmanufacturing/production/2015/06"><resources>
    <object id="1" type="model">${mesh}</object><object id="2" type="model">${mesh}</object>
    <object id="3" type="model" name="asm"><components><component objectid="1" transform="1 0 0 0 1 0 0 0 1 0 0 0"/><component objectid="2" transform="1 0 0 0 1 0 0 0 1 20 0 0"/></components></object>
    <object id="4" type="support">${mesh}</object></resources>
    <build><item objectid="3" transform="1 0 0 0 1 0 0 0 1 5 5 0"/><item objectid="4" printable="1"/><item objectid="1" printable="0"/></build></model>`;
  const settings = '<config><object id="3"><metadata key="name" value="Assembly"/><part id="1" subtype="normal_part"/><part id="2" subtype="modifier_part"/></object></config>';
  const zip = writeZip([{ name: '3D/3dmodel.model', data: model }, { name: 'Metadata/model_settings.config', data: settings }]);
  const r = parse3mf(zip, { fileName: 'asm.3mf' });
  assert.strictEqual(r.objects.length, 1);
  assert.strictEqual(r.objects[0].name, 'Assembly');
  assert.strictEqual(r.objects[0].positions.length / 9, 12, 'modifier part skipped');
  assert.ok(r.warnings.includes('modifier_part'));
  const b = G.bounds(r.objects[0].positions);
  assert.deepStrictEqual(b.size.map((v) => Math.round(v)), [100, 100, 100], 'centimeters become millimeters');
  assert.ok(r.objects[0].paint && r.objects[0].paint[0] === 1);
  const item = processBuffer(zip, 'asm.3mf');
  assert.strictEqual(item.info.kind, '3mf');
  assert.deepStrictEqual(item.info.dims, [100, 100, 100]);
  assert.deepStrictEqual(parseModelSettings(''), new Map());
  assert.throws(() => parse3mf(writeZip([{ name: 'x.txt', data: 'x' }])), /no 3D model/);
  assert.throws(() => parse3mf(Buffer.from('nope')), /bad-3mf/);
  const none = writeZip([{ name: '3D/3dmodel.model', data: '<model><resources></resources><build><item objectid="9"/></build></model>' }]);
  assert.throws(() => parse3mf(none), /empty/);
});

