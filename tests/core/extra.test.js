test('law: in a big file (megabytes of moves) the header and the tail are still found, the path is cut to the budget', () => {
  const orca = fs.readFileSync(path.join(FIX, 'orca.gcode'), 'utf8');
  const cut = orca.indexOf('; EXECUTABLE_BLOCK_END');
  const filler = [];
  for (let i = 0; i < 80000; i++) filler.push(`G1 X${100 + (i % 50)} Y${100 + ((i * 7) % 50)} E0.01`);
  const big = orca.slice(0, cut) + filler.join('\n') + '\n' + orca.slice(cut);
  assert.ok(big.length > 1024 * 1024);
  const r = processBuffer(Buffer.from(big), 'big.gcode', { budget: 5000 });
  assert.strictEqual(r.info.timeSec, 3723);
  assert.strictEqual(r.info.filamentG, 3.69);
  assert.strictEqual(r.info.printer, 'Elegoo Centauri Carbon 0.4 nozzle');
  assert.ok(r.view.segments <= 5000);
  assert.ok(r.view.sourceSegments > 80000);
});

