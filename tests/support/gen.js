// Образцы G-code «как пишет слайсер X»: одна и та же коробочка (стенки, заполнение, юбка, крышка)
// с шапкой и хвостом в формате каждого слайсера. Значения шапки берутся из spec - они же эталон
// в tests/fixtures/expected.json, а разбор (src/core/meta.js) читает файл сам.
'use strict';
const zlib = require('zlib');
const { pngEncode } = require('../../src/core/thumbs');
const { qoiEncode } = require('./encoders');

const fmt = (v) => String(Math.round(v * 1000) / 1000);

/** Картинка w x h: градиент и квадрат по центру (детерминированная). */
function picture(w, h, hue = 0) {
  const rgba = Buffer.alloc(w * h * 4);
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const o = (y * w + x) * 4;
      const inside = x > w / 4 && x < (3 * w) / 4 && y > h / 4 && y < (3 * h) / 4;
      rgba[o] = inside ? 255 : (x * 255 / w + hue) & 255;
      rgba[o + 1] = inside ? 128 : (y * 255 / h) & 255;
      rgba[o + 2] = inside ? 0 : 90;
      rgba[o + 3] = 255;
    }
  }
  return rgba;
}

function thumbBlock(tag, w, h, data) {
  const b64 = data.toString('base64');
  const lines = [`; ${tag} begin ${w}x${h} ${b64.length}`];
  for (let i = 0; i < b64.length; i += 78) lines.push('; ' + b64.slice(i, i + 78));
  lines.push(`; ${tag} end`, ';', '');
  return lines;
}

const NAMES = {
  orca: { outer: 'Outer wall', inner: 'Inner wall', sparse: 'Sparse infill', top: 'Top surface', bottom: 'Bottom surface', skirt: 'Skirt' },
  prusa: { outer: 'External perimeter', inner: 'Perimeter', sparse: 'Internal infill', top: 'Top solid infill', bottom: 'Solid infill', skirt: 'Skirt/Brim' },
  cura: { outer: 'WALL-OUTER', inner: 'WALL-INNER', sparse: 'FILL', top: 'SKIN', bottom: 'SKIN', skirt: 'SKIRT' },
};

/**
 * Тело: коробочка box {x0, y0, w, d, h}, слой lh. flavor задаёт метки слоя и типов.
 * Возвращает строки G-code и сколько выдавлено (мм) - для проверки законов.
 */
function body(flavor, { box, lh }) {
  const out = [];
  const names = NAMES[flavor === 'bambu' ? 'orca' : flavor] || NAMES.orca;
  const absE = flavor === 'cura';
  let e = 0, mm = 0;
  const n = Math.round(box.h / lh);
  const type = (t) => (flavor === 'bambu' ? `; FEATURE: ${names[t]}` : `;TYPE:${names[t]}`);
  const ext = (x, y, len) => {
    const de = len * 0.0333;
    mm += de;
    e += de;
    return `G1 X${fmt(x)} Y${fmt(y)} E${fmt(absE ? e : de)}`;
  };
  const square = (x0, y0, w, d) => {
    const pts = [[x0 + w, y0], [x0 + w, y0 + d], [x0, y0 + d], [x0, y0]];
    let px = x0, py = y0;
    const lines = [`G0 X${fmt(x0)} Y${fmt(y0)} F12000`];
    for (const [x, y] of pts) { lines.push(ext(x, y, Math.hypot(x - px, y - py))); px = x; py = y; }
    return lines;
  };
  out.push(absE ? 'M82' : 'M83', 'G90', 'G92 E0');
  if (flavor === 'cura') out.push(`;LAYER_COUNT:${n}`);
  for (let l = 0; l < n; l++) {
    const z = Math.round((l + 1) * lh * 1000) / 1000;
    if (flavor === 'orca' || flavor === 'prusa') out.push(';LAYER_CHANGE', `;Z:${fmt(z)}`, `;HEIGHT:${fmt(lh)}`);
    else if (flavor === 'bambu') out.push('; CHANGE_LAYER', `; Z_HEIGHT: ${fmt(z)}`, `; LAYER_HEIGHT: ${fmt(lh)}`);
    else if (flavor === 'cura') out.push(`;LAYER:${l}`);
    out.push(`G1 Z${fmt(z)} F720`);
    if (l === 0) { out.push(type('skirt'), ...square(box.x0 - 5, box.y0 - 5, box.w + 10, box.d + 10)); }
    out.push(type('outer'), ...square(box.x0, box.y0, box.w, box.d));
    out.push(type('inner'), ...square(box.x0 + 0.45, box.y0 + 0.45, box.w - 0.9, box.d - 0.9));
    const fill = l < 2 ? 'bottom' : l >= n - 2 ? 'top' : 'sparse';
    out.push(type(fill));
    const step = fill === 'sparse' ? 4 : 0.9;
    for (let x = box.x0 + 1, k = 0; x < box.x0 + box.w - 1; x += step, k++) {
      const y1 = k % 2 ? box.y0 + 1 : box.y0 + box.d - 1;
      const y0 = k % 2 ? box.y0 + box.d - 1 : box.y0 + 1;
      out.push(`G0 X${fmt(x)} Y${fmt(y0)} F12000`, ext(x, y1, Math.abs(y1 - y0)));
    }
    out.push(absE ? `G1 E${fmt(e - 0.8)} F2400` : 'G1 E-0.8 F2400', `G0 Z${fmt(z + 0.4)} F720`);
    if (absE) out.push('G92 E' + fmt(e - 0.8), `G1 E${fmt(e)} F2400`);
    else out.push('G1 E0.8 F2400');
    if (flavor === 'cura') out.push(`;TIME_ELAPSED:${(l + 1) * 60}`);
  }
  return { lines: out, mm, layers: n };
}

function start(spec) {
  return [`M140 S${spec.bedTemp}`, `M104 S${spec.nozzleTemp}`, `M190 S${spec.bedTemp}`, `M109 S${spec.nozzleTemp}`, 'G28', 'M107'];
}

/** G-code одного вида. spec - см. tools/make-fixtures.js. */
function makeGcode(spec) {
  const b = body(spec.flavor, spec);
  const t = spec.time;
  const lines = [];
  const png = spec.thumb ? pngEncode(spec.thumb, spec.thumb, picture(spec.thumb, spec.thumb)) : null;
  if (spec.flavor === 'orca') {
    lines.push('; HEADER_BLOCK_START', `; generated by ${spec.slicer} ${spec.version} on ${spec.date.replace('T', ' at ')}`);
    if (spec.ccVersion) lines.push(`; Slicer CC ${spec.ccVersion}`);
    lines.push(`; total layer number: ${b.layers}`, `; estimated printing time (normal mode) = ${t}`, '; HEADER_BLOCK_END', '');
    if (png) lines.push('; THUMBNAIL_BLOCK_START', ...thumbBlock('thumbnail', spec.thumb, spec.thumb, png), '; THUMBNAIL_BLOCK_END', '');
    lines.push('; EXECUTABLE_BLOCK_START', ...start(spec), ...b.lines, '; EXECUTABLE_BLOCK_END', '');
    lines.push(`; filament used [mm] = ${spec.mm}`, `; filament used [cm3] = ${spec.cm3}`, `; filament used [g] = ${spec.g}`, '; filament cost = 0.07',
      `; total filament used [g] = ${spec.g}`, '; total filament cost = 0.07', `; total layers count = ${b.layers}`, `; estimated printing time (normal mode) = ${t}`, '');
    lines.push('; CONFIG_BLOCK_START', `; curr_bed_type = ${spec.plate}`, `; filament_colour = ${spec.color}`, `; filament_density = ${spec.density}`,
      '; filament_diameter = 1.75', `; filament_settings_id = "${spec.filamentName}"`, `; filament_type = ${spec.filamentType}`,
      `; hot_plate_temp = ${spec.bedTemp + 5}`, `; textured_plate_temp = ${spec.bedTemp}`, `; layer_height = ${spec.lh}`, `; nozzle_diameter = ${spec.nozzle}`,
      `; nozzle_temperature = ${spec.nozzleTemp}`, `; nozzle_temperature_initial_layer = ${spec.nozzleTemp + 5}`,
      `; printable_area = 0x0,${spec.bed[0]}x0,${spec.bed[0]}x${spec.bed[1]},0x${spec.bed[1]}`, `; printable_height = ${spec.bed[2]}`,
      `; printer_model = ${spec.printerModel}`, `; printer_settings_id = ${spec.printer}`, `; print_settings_id = ${spec.process}`, '; CONFIG_BLOCK_END', '');
  } else if (spec.flavor === 'prusa') {
    lines.push(`; generated by PrusaSlicer ${spec.version}+win64 on ${spec.date.replace('T', ' at ')} UTC`, ';', '');
    if (spec.qoi) lines.push(...thumbBlock('thumbnail_QOI', spec.qoi, spec.qoi, qoiEncode(spec.qoi, spec.qoi, picture(spec.qoi, spec.qoi, 60))));
    if (png) lines.push(...thumbBlock('thumbnail', spec.thumb, spec.thumb, png));
    lines.push('; external perimeters extrusion width = 0.45mm', '; perimeters extrusion width = 0.45mm', '', 'M73 P0 R25', ...start(spec), ...b.lines, 'M73 P100 R0', '');
    lines.push(...prusaFooter(spec), '', '; prusaslicer_config = begin', ...Object.entries(prusaConfig(spec)).map(([k, v]) => `; ${k} = ${v}`), '; prusaslicer_config = end', '');
  } else if (spec.flavor === 'bambu') {
    lines.push('; HEADER_BLOCK_START', `; BambuStudio ${spec.version}`, `; model printing time: 55m 3s; total estimated time: ${t}`, `; total layer number: ${b.layers}`,
      `; total filament length [mm] : ${spec.mm}`, `; total filament volume [cm^3] : ${Math.round(spec.cm3 * 1000)}`, `; total filament weight [g] : ${spec.g}`,
      `; filament_density: ${spec.density}`, '; filament_diameter: 1.75', `; max_z_height: ${spec.box.h}`, '; HEADER_BLOCK_END', '');
    if (png) lines.push('; THUMBNAIL_BLOCK_START', ...thumbBlock('thumbnail', spec.thumb, spec.thumb, png), '; THUMBNAIL_BLOCK_END', '');
    lines.push('; EXECUTABLE_BLOCK_START', ...start(spec), ...b.lines, '; EXECUTABLE_BLOCK_END', '');
    lines.push('; CONFIG_BLOCK_START', `; curr_bed_type = ${spec.plate}`, `; filament_colour = ${spec.color}`, `; filament_type = ${spec.filamentType}`,
      `; filament_settings_id = "${spec.filamentName}"`, `; hot_plate_temp = ${spec.bedTemp + 10}`, `; textured_plate_temp = ${spec.bedTemp}`,
      `; layer_height = ${spec.lh}`, `; nozzle_diameter = ${spec.nozzle}`, `; nozzle_temperature = ${spec.nozzleTemp}`,
      `; printable_area = 0x0,${spec.bed[0]}x0,${spec.bed[0]}x${spec.bed[1]},0x${spec.bed[1]}`, `; printable_height = ${spec.bed[2]}`,
      `; printer_model = ${spec.printerModel}`, `; printer_settings_id = ${spec.printer}`, '; CONFIG_BLOCK_END', '');
  } else if (spec.flavor === 'cura') {
    if (spec.griffin) {
      lines.push(';START_OF_HEADER', ';HEADER_VERSION:0.1', ';FLAVOR:Griffin', ';GENERATOR.NAME:Cura_SteamEngine', `;GENERATOR.VERSION:${spec.version}`,
        ';GENERATOR.BUILD_DATE:2023-12-05', `;TARGET_MACHINE.NAME:${spec.printer}`, `;EXTRUDER_TRAIN.0.INITIAL_TEMPERATURE:${spec.nozzleTemp}`,
        `;EXTRUDER_TRAIN.0.MATERIAL.VOLUME_USED:${spec.volume}`, `;EXTRUDER_TRAIN.0.NOZZLE.DIAMETER:${spec.nozzle}`, ';EXTRUDER_TRAIN.0.NOZZLE.NAME:AA 0.4',
        ';BUILD_PLATE.TYPE:glass', `;BUILD_PLATE.INITIAL_TEMPERATURE:${spec.bedTemp}`, `;PRINT.TIME:${spec.timeSec}`, ';PRINT.GROUPS:1', ';END_OF_HEADER');
    } else {
      lines.push(';FLAVOR:Marlin', `;TIME:${spec.timeSec}`, `;Filament used: ${spec.mm / 1000}m`, `;Layer height: ${spec.lh}`, ';MINX:90', ';MINY:90', ';MINZ:0.2',
        ';MAXX:130', ';MAXY:130', `;MAXZ:${spec.box.h}`, `;TARGET_MACHINE.NAME:${spec.printer}`, `;Generated with Cura_SteamEngine ${spec.version}`);
    }
    if (png) lines.push(...thumbBlock('thumbnail', spec.thumb, spec.thumb, png));
    lines.push(...start(spec), ...b.lines, 'M107', 'M104 S0', 'M140 S0', ';End of Gcode');
    const g = `[general]\\nversion = 4\\nname = Standard\\ndefinition = custom\\n\\n[values]\\nlayer_height = ${spec.lh}\\n`;
    const x = `[general]\\nversion = 4\\n\\n[values]\\nmaterial_diameter = ${spec.diameter || 1.75}\\nmaterial_type = ${spec.filamentType}\\n`;
    const json = `{"global_quality": "${g}", "extruder_quality": ["${x}"]}`;
    for (let i = 0; i < json.length; i += 69) lines.push(';SETTING_3 ' + json.slice(i, i + 69));
  }
  return { text: lines.join('\n') + '\n', layers: b.layers, extrudedMm: b.mm };
}

function prusaFooter(spec) {
  return [`; filament used [mm] = ${spec.mm}`, `; filament used [cm3] = ${spec.cm3}`, `; filament used [g] = ${spec.g}`, '; filament cost = 0.08',
    `; total filament used [g] = ${spec.g}`, '; total filament cost = 0.08', `; estimated printing time (normal mode) = ${spec.time}`,
    '; estimated first layer printing time (normal mode) = 1m 2s'];
}

function prusaConfig(spec) {
  return {
    bed_shape: `0x0,${spec.bed[0]}x0,${spec.bed[0]}x${spec.bed[1]},0x${spec.bed[1]}`, bed_temperature: spec.bedTemp, filament_colour: spec.color,
    filament_density: spec.density, filament_diameter: 1.75, filament_settings_id: `"${spec.filamentName}"`, filament_type: spec.filamentType,
    first_layer_temperature: spec.nozzleTemp + 5, layer_height: spec.lh, max_print_height: spec.bed[2], nozzle_diameter: spec.nozzle,
    printer_model: spec.printerModel, printer_settings_id: spec.printer, temperature: spec.nozzleTemp,
  };
}

/** Модель-кубик w мм: 12 треугольников. */
function cube(w = 20, h = w) {
  const v = [[0, 0, 0], [w, 0, 0], [w, w, 0], [0, w, 0], [0, 0, h], [w, 0, h], [w, w, h], [0, w, h]];
  const f = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]];
  return Float32Array.from(f.flatMap((t) => t.flatMap((i) => v[i])));
}

function stlBinary(pos) {
  const n = pos.length / 9;
  const buf = Buffer.alloc(84 + n * 50);
  buf.write('binary stl', 0, 'latin1');
  buf.writeUInt32LE(n, 80);
  for (let t = 0; t < n; t++) for (let k = 0; k < 9; k++) buf.writeFloatLE(pos[t * 9 + k], 84 + t * 50 + 12 + k * 4);
  return buf;
}

function stlAscii(pos, name = 'cube') {
  const out = [`solid ${name}`];
  for (let t = 0; t < pos.length; t += 9) {
    out.push('  facet normal 0 0 0', '    outer loop');
    for (let k = 0; k < 9; k += 3) out.push(`      vertex ${pos[t + k]} ${pos[t + k + 1]} ${pos[t + k + 2]}`);
    out.push('    endloop', '  endfacet');
  }
  out.push(`endsolid ${name}`);
  return Buffer.from(out.join('\n') + '\n');
}

function model3mfXml(pos, { x = 0, y = 0 } = {}) {
  const verts = [], tris = [], map = new Map();
  for (let i = 0; i < pos.length; i += 3) {
    const k = `${pos[i]} ${pos[i + 1]} ${pos[i + 2]}`;
    if (!map.has(k)) { map.set(k, verts.length); verts.push(k); }
    tris.push(map.get(k));
  }
  const v = verts.map((s) => { const [a, b, c] = s.split(' '); return `<vertex x="${a}" y="${b}" z="${c}"/>`; }).join('');
  const t = [];
  for (let i = 0; i < tris.length; i += 3) t.push(`<triangle v1="${tris[i]}" v2="${tris[i + 1]}" v3="${tris[i + 2]}"/>`);
  return '<?xml version="1.0" encoding="UTF-8"?>\n<model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02">' +
    `<resources><object id="1" type="model" name="cube"><mesh><vertices>${v}</vertices><triangles>${t.join('')}</triangles></mesh></object></resources>` +
    `<build><item objectid="1" transform="1 0 0 0 1 0 0 0 1 ${x} ${y} 0"/></build></model>`;
}

